#!/usr/bin/env python3
"""Concatenate the ordered CSS modules into one bundle and point the pages at it.

Every page used to open eight render-blocking stylesheet requests
(site.css, profiles.css, project-atmospheres.css, migration.css,
profile-themes.css, page-layouts.css, bagley.css, overrides.css). The cascade
order matters and is preserved here verbatim: the modules are concatenated in
MODULE_ORDER, which is the order the pages linked them in.

The module files stay in the repository as the editable source of truth; the
bundle is generated and carries a "do not edit" banner. Pages lose eight
requests and one critical-path tail, and the bundle is content-hashed by
tools/bust_cache.py just like the modules were, so it can be cached immutably.

Run from the repo root:  python3 tools/bundle_css.py && python3 tools/bust_cache.py

Idempotent: re-running rewrites bundle.css from the current modules and leaves
the HTML alone once it already points at the bundle.
"""

from __future__ import annotations

import re
from pathlib import Path

# Cascade order. This is the order every page linked the modules in, and it is
# load-bearing: later files override earlier ones (overrides.css must stay last).
MODULE_ORDER = [
    "site.css",
    "profiles.css",
    "project-atmospheres.css",
    "migration.css",
    "profile-themes.css",
    "page-layouts.css",
    "bagley.css",
    "module-directory.css",
    "changelog.css",
    "glyphsmith.css",
    "overrides.css",
]

BUNDLE_NAME = "bundle.css"

BANNER = """/* Generated by tools/bundle_css.py - do not edit.
 *
 * One stylesheet for every page, so the first paint waits on a single request
 * instead of eight. Sources, in cascade order:
{modules}
 * Edit the modules (and re-run tools/bundle_css.py && tools/bust_cache.py);
 * editing this file directly loses the change on the next build.
 */

"""

LINK_BLOCK = re.compile(
    r'(?:[ \t]*<link rel="stylesheet" href="/css/(?:'
    + "|".join(re.escape(m.removesuffix(".css")) for m in MODULE_ORDER)
    + r'|bundle)\.css(?:\?v=[\w-]+)?">[ \t]*\r?\n?)+'
)


def build_bundle(root: Path) -> tuple[int, int]:
    modules = [root / "css" / name for name in MODULE_ORDER]
    missing = [path.name for path in modules if not path.is_file()]
    if missing:
        raise SystemExit(f"missing css modules: {', '.join(missing)}")

    banner = BANNER.format(modules="".join(f" *   - {name}\n" for name in MODULE_ORDER))
    chunks = [banner]
    for path in modules:
        body = path.read_text(encoding="utf-8").rstrip("\n")
        chunks.append(f"/* ===== css/{path.name} ===== */\n{body}\n\n")

    bundle = "".join(chunks).rstrip("\n") + "\n"
    # Belt and braces: the site never used @import/@charset, so the join above is
    # a pure concatenation. Assert it, because @import in a concatenated file
    # would silently stop working.
    for path in modules:
        head = path.read_text(encoding="utf-8")[:200]
        if "@import" in head or "@charset" in head:
            raise SystemExit(
                f"css/{path.name} starts with @import/@charset - concatenation would break it"
            )

    destination = root / "css" / BUNDLE_NAME
    destination.write_text(bundle, encoding="utf-8")
    return sum(path.stat().st_size for path in modules), destination.stat().st_size


def relink_pages(root: Path) -> int:
    changed = 0
    for html in sorted(root.rglob("*.html")):
        if ".git" in html.parts:
            continue
        source = html.read_text(encoding="utf-8", errors="replace")
        # Keep the first link's own indentation for the replacement line.
        match = LINK_BLOCK.search(source)
        if not match:
            continue
        indent = re.match(r"[ \t]*", match.group(0)).group(0)
        replacement = f'{indent}<link rel="stylesheet" href="/css/{BUNDLE_NAME}">\n'
        updated = LINK_BLOCK.sub(replacement, source, count=1)
        if updated != source:
            html.write_text(updated, encoding="utf-8")
            changed += 1
    return changed


def main() -> None:
    root = Path(__file__).resolve().parent.parent
    before, after = build_bundle(root)
    changed = relink_pages(root)
    print(
        f"bundle: {len(MODULE_ORDER)} modules {before / 1024:.1f} KiB -> css/{BUNDLE_NAME} {after / 1024:.1f} KiB; "
        f"relinked {changed} page(s)"
    )


if __name__ == "__main__":
    main()
